using System.Text;
using RobloxCS.TypeGenerator.Models;
using Serilog;

namespace RobloxCS.TypeGenerator;

internal sealed class DataTypeGenerator {
    private const string Body = "ThrowHelper.ThrowTranspiledMethod();";

    public static readonly HashSet<string> HandWritten = [
        "RBXScriptSignal", "RBXScriptConnection", "SharedTable", "Secret", "Content",
        "Enum", "EnumItem", "Enums", "Instance", "Tuple", "Variant",
    ];

    private static readonly HashSet<string> BinaryOperators = ["+", "-", "*", "/", "%"];

    private static readonly HashSet<string> CSharpKeywords = [
        "abstract", "as", "base", "bool", "break", "byte", "case", "catch", "char", "checked", "class", "const", "continue",
        "decimal", "default", "delegate", "do", "double", "else", "enum", "event", "explicit", "extern", "false", "finally",
        "fixed", "float", "for", "foreach", "goto", "if", "implicit", "in", "int", "interface", "internal", "is", "lock",
        "long", "namespace", "new", "null", "object", "operator", "out", "override", "params", "private", "protected",
        "public", "readonly", "ref", "return", "sbyte", "sealed", "short", "sizeof", "stackalloc", "static", "string",
        "struct", "switch", "this", "throw", "true", "try", "typeof", "uint", "ulong", "unchecked", "unsafe", "ushort",
        "using", "virtual", "void", "volatile", "while",
    ];

    private readonly IReadOnlyDictionary<string, DocDataType> _dataTypes;
    private readonly Func<string, string?> _resolveNamed;

    public DataTypeGenerator(IReadOnlyDictionary<string, DocDataType> dataTypes, Func<string, string?> resolveNamed) {
        _dataTypes = dataTypes;
        _resolveNamed = resolveNamed;
    }

    public static bool IsReferenceType(string name) => name.EndsWith("Params", StringComparison.Ordinal) || name is "Random";

    public Dictionary<string, string> Generate() {
        var result = new Dictionary<string, string>();

        foreach (var (name, doc) in _dataTypes.OrderBy(pair => pair.Key, StringComparer.Ordinal)) {
            if (HandWritten.Contains(name)) {
                Log.Verbose("Skipping hand-written datatype {DataType}", name);

                continue;
            }

            result[$"DataType{name}.g.cs"] = GenerateOne(name, doc);
        }

        Log.Information("Generated {Count} datatypes from creator docs", result.Count);

        return result;
    }

    private string GenerateOne(string name, DocDataType doc) {
        var isClass = IsReferenceType(name);
        var builder = new StringBuilder();
        var signatures = new HashSet<string>(StringComparer.Ordinal);
        var memberNames = new HashSet<string>(StringComparer.Ordinal);
        var valueNames = new HashSet<string>(StringComparer.Ordinal);

        builder.AppendLine("/// <auto-generated>");
        builder.AppendLine("/// Auto-generated by RobloxCS.TypeGenerator (https://github.com/glomdom/RobloxCS)");
        builder.AppendLine("/// </auto-generated>");
        builder.AppendLine("#nullable enable");
        builder.AppendLine("#pragma warning disable CS0660, CS0661");
        builder.AppendLine("namespace RobloxCS.Types;");
        builder.AppendLine($"[RobloxNative(\"{name}\", RobloxNativeType.DataType)]");
        builder.AppendLine(isClass ? $"public sealed class {name} {{" : $"public readonly struct {name} {{");

        var constructors = doc.Constructors ?? [];
        var hasParameterizedNew = constructors.Any(ctor => MemberOf(ctor.Name) == "new" && ctor.Parameters is { Count: > 0 });

        foreach (var ctor in constructors) {
            var member = MemberOf(ctor.Name);
            var (parameters, signature) = FormatParameters(ctor.Parameters);

            if (member == "new") {
                if (parameters.Length == 0 && (!isClass || !hasParameterizedNew)) {
                    continue;
                }

                if (signatures.Add($"ctor({signature})")) {
                    builder.AppendLine($"    public {name}({parameters}) {{ }}");
                }

                continue;
            }

            var csName = Pascal(member);
            if (!signatures.Add($"static {csName}({signature})")) {
                continue;
            }

            memberNames.Add(csName);
            AppendRobloxName(builder, csName, member);
            builder.AppendLine($"    public static {name} {csName}({parameters}) => {Body}");
        }

        var constants = new HashSet<string>(StringComparer.Ordinal);

        foreach (var constant in doc.Constants ?? []) {
            var member = MemberOf(constant.Name);
            var csName = SafeMemberName(Pascal(member), name);

            if (!memberNames.Add(csName)) {
                continue;
            }

            constants.Add(member);
            valueNames.Add(csName);
            AppendRobloxName(builder, csName, member);
            builder.AppendLine($"    public static {DocType(constant.Type)} {csName} => {Body}");
        }

        foreach (var property in doc.Properties ?? []) {
            var member = MemberOf(property.Name);
            if (constants.Contains(member)) {
                continue;
            }

            var csName = SafeMemberName(Pascal(member), name);
            if (!memberNames.Add(csName)) {
                Log.Warning("Skipping duplicate member {DataType}.{Member}", name, csName);

                continue;
            }

            var type = DocType(property.Type);
            valueNames.Add(csName);

            AppendRobloxName(builder, csName, member);
            builder.AppendLine(isClass
                ? $"    public {type} {csName} {{ get; set; }} = default!;"
                : $"    public {type} {csName} => {Body}");
        }

        AppendMethods(builder, doc.Methods, name, isStatic: false, signatures, valueNames);
        AppendMethods(builder, doc.Functions, name, isStatic: true, signatures, valueNames);
        AppendOperators(builder, doc.MathOperations ?? [], name, isClass, signatures);

        builder.AppendLine("}");

        return builder.ToString();
    }

    private void AppendMethods(StringBuilder builder, List<DocMember>? methods, string owner, bool isStatic, HashSet<string> signatures, HashSet<string> valueNames) {
        foreach (var method in (methods ?? []).SelectMany(WithSingleValueOverload)) {
            var member = MemberOf(method.Name);
            var csName = SafeMemberName(Pascal(member), owner);
            var (parameters, signature) = FormatParameters(method.Parameters);

            if (valueNames.Contains(csName)) {
                Log.Warning("Skipping {DataType}.{Member}, a property already has that name", owner, csName);

                continue;
            }

            if (!signatures.Add($"{csName}({signature})")) {
                continue;
            }

            var modifiers = isStatic ? "public static" : "public";

            AppendRobloxName(builder, csName, member);
            builder.AppendLine($"    {modifiers} {ReturnType(method.Returns)} {csName}({parameters}) => {Body}");
        }
    }

    private static IEnumerable<DocMember> WithSingleValueOverload(DocMember method) {
        if (method.Parameters is not [.., { Name: "...", Type: { } variadic }] || TupleInner(variadic) is not { } element) {
            yield return method;

            yield break;
        }

        var returns = method.Returns is [{ Type: { } returned }] && TupleInner(returned) == element
            ? [new DocReturn { Type = element }]
            : method.Returns;

        yield return new DocMember {
            Name = method.Name,
            Parameters = [.. method.Parameters.SkipLast(1), new DocParameter { Name = "value", Type = element }],
            Returns = returns,
        };

        yield return method;
    }

    private static string? TupleInner(string raw) {
        return raw.StartsWith("Tuple<", StringComparison.Ordinal) && raw.EndsWith('>') ? raw["Tuple<".Length..^1] : null;
    }

    private void AppendOperators(StringBuilder builder, List<DocMathOperation> operations, string name, bool isClass, HashSet<string> signatures) {
        var hasSelfSubtraction = false;

        foreach (var operation in operations) {
            if (!BinaryOperators.Contains(operation.Operation)) {
                continue;
            }

            if (operation.TypeB is null) {
                if (operation.Operation == "-" && signatures.Add("unary-")) {
                    builder.AppendLine($"    public static {name} operator -({name} value) => {Body}");
                }

                continue;
            }

            var left = DocType(operation.TypeA);
            var right = DocType(operation.TypeB);
            var result = DocType(operation.ReturnType);

            if (left != name && right != name) {
                continue;
            }

            if (operation.Operation == "-" && left == name && right == name) {
                hasSelfSubtraction = true;
            }

            if (signatures.Add($"op{operation.Operation}({left},{right})")) {
                builder.AppendLine($"    public static {result} operator {operation.Operation}({left} a, {right} b) => {Body}");
            }
        }

        if (hasSelfSubtraction && signatures.Add("unary-")) {
            builder.AppendLine($"    public static {name} operator -({name} value) => {Body}");
        }

        if (!isClass) {
            builder.AppendLine($"    public static bool operator ==({name} a, {name} b) => {Body}");
            builder.AppendLine($"    public static bool operator !=({name} a, {name} b) => {Body}");
        }
    }

    private (string Text, string Signature) FormatParameters(List<DocParameter>? parameters) {
        var list = parameters ?? [];

        var firstOptional = list.Count;
        while (firstOptional > 0 && (list[firstOptional - 1].IsOptional || list[firstOptional - 1].Name == "...")) {
            firstOptional--;
        }

        var parts = new List<string>();
        var types = new List<string>();

        for (var index = 0; index < list.Count; index++) {
            var parameter = list[index];

            if (parameter.Name == "...") {
                var element = TupleElement(parameter.Type);

                parts.Add($"params {element}[] values");
                types.Add($"{element}[]");

                break;
            }

            var type = DocType(parameter.Type);
            if (type == "void") {
                type = "object?";
            }

            var optional = index >= firstOptional ? " = default!" : string.Empty;

            parts.Add($"{type} {SafeName(parameter.Name)}{optional}");
            types.Add(type.TrimEnd('?'));
        }

        return (string.Join(", ", parts), string.Join(",", types));
    }

    private string ReturnType(List<DocReturn>? returns) {
        var types = (returns ?? [])
            .Select(entry => DocType(entry.Type))
            .Where(type => type != "void")
            .ToList();

        return types.Count switch {
            0 => "void",
            1 => types[0],
            _ => $"({string.Join(", ", types)})",
        };
    }

    private string TupleElement(string? raw) {
        return raw is not null && TupleInner(raw) is { } inner ? DocType(inner) : "object";
    }

    private string DocType(string? raw) {
        if (string.IsNullOrWhiteSpace(raw)) {
            return "object";
        }

        var type = raw.Trim();
        var optional = type.EndsWith('?');
        if (optional) {
            type = type[..^1].Trim();
        }

        var resolved = ResolveType(type);

        return optional && resolved != "void" && !resolved.EndsWith('?') ? $"{resolved}?" : resolved;
    }

    private string ResolveType(string type) {
        if (type.Contains('|') || type.Contains("->") || type.StartsWith('(') && type != "()") {
            return "object";
        }

        if (type.StartsWith('{') && type.EndsWith('}')) {
            var inner = type[1..^1].Trim();

            return inner.Contains(':') || inner.Contains('[') ? "Dictionary<object, object>" : $"List<{DocType(inner)}>";
        }

        if (type.StartsWith("Array<", StringComparison.Ordinal) && type.EndsWith('>')) {
            return $"List<{DocType(type["Array<".Length..^1])}>";
        }

        if (type.StartsWith("Tuple", StringComparison.Ordinal)) {
            return "LuaTuple";
        }

        switch (type) {
            case "number" or "float" or "double": return "double";
            case "int": return "int";
            case "int64": return "long";
            case "bool" or "boolean": return "bool";
            case "string": return "string";
            case "()" or "nil" or "null" or "void": return "void";
            case "table" or "Variant" or "any": return "object";
            case "Array": return "List<object>";
            case "Dictionary": return "Dictionary<string, object>";
            case "Function": return "Delegate";
            case "Content" or "ContentId": return "string";
        }

        if (_dataTypes.ContainsKey(type) || HandWritten.Contains(type) || type is "LuaTuple" or "Buffer") {
            return type;
        }

        if (type.StartsWith("Enum.", StringComparison.Ordinal)) {
            return $"Enums.{type["Enum.".Length..]}";
        }

        if (_resolveNamed(type) is { } named) {
            return named;
        }

        Log.Warning("Unknown type {Type} in creator docs, using object", type);

        return "object";
    }

    private static string MemberOf(string qualified) {
        var separator = qualified.LastIndexOfAny(['.', ':']);

        return separator < 0 ? qualified : qualified[(separator + 1)..];
    }

    private static string Pascal(string name) => name.Length == 0 ? name : char.ToUpperInvariant(name[0]) + name[1..];
    private static string SafeMemberName(string name, string owner) => name == owner ? "Value" : name;

    private static string SafeName(string name) {
        var cleaned = new string(name.Where(character => char.IsAsciiLetterOrDigit(character) || character == '_').ToArray());
        if (cleaned.Length == 0) {
            cleaned = "arg";
        }

        return CSharpKeywords.Contains(cleaned) ? $"@{cleaned}" : cleaned;
    }

    private static void AppendRobloxName(StringBuilder builder, string csName, string robloxName) {
        if (csName != robloxName) {
            builder.AppendLine($"    [RobloxName(\"{robloxName}\")]");
        }
    }
}